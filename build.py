"""Build the hosted page, the claude.ai copy and the server's copy of the game core.

cheek-pouch.html is the page source; its /* SIM:INLINE */ marker is where the shared
game core (game/sim.js) goes. The same core is copied to the API, which replays Daily
Burrow runs with it, so the browser and the server always run identical code.

Writes index.html (GitHub Pages), dist/cheek-pouch.html (claude.ai) and api/src/sim.gen.js.

Run: python3 build.py
"""
from pathlib import Path

# The site's public address, e.g. "https://play.example.com/" (keep the
# trailing slash). Link previews on X, Discord and Telegram need the full
# address of the cover image, so set this once the domain is live and rebuild.
SITE_URL = "https://cheek-pouch.live/"

ROOT = Path(__file__).parent
TITLE = "Cheek Pouch"
DESCRIPTION = "An endless hamster arcade game run by a real hamster's wheel on Squeekchain."
COVER = SITE_URL + "art/cheek-pouch-cover.png"

HEAD = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>{TITLE}</title>
<meta name="description" content="{DESCRIPTION}">
<meta name="squeekchain-project" content="430e9294-1c8e-4e18-aacc-e1dab9dd0462">
<link rel="icon" type="image/png" href="art/cheek-pouch-icon.png">
<link rel="apple-touch-icon" href="art/cheek-pouch-icon.png">
<meta property="og:type" content="website">
<meta property="og:title" content="{TITLE}">
<meta property="og:description" content="{DESCRIPTION}">
<meta property="og:image" content="{COVER}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="A crowned hamster with stuffed cheeks catching sunflower seeds at night">
{f'<meta property="og:url" content="{SITE_URL}">' if SITE_URL else ''}
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{TITLE}">
<meta name="twitter:description" content="{DESCRIPTION}">
<meta name="twitter:image" content="{COVER}">
<style>body{{margin:0}}img{{max-width:100%}}</style></head><body>
"""

MARKER = "/* SIM:INLINE */"
sim = (ROOT / "game" / "sim.js").read_text(encoding="utf-8")
page = (ROOT / "cheek-pouch.html").read_text(encoding="utf-8")
assert page.count(MARKER) == 1, "cheek-pouch.html needs exactly one /* SIM:INLINE */ marker"
page = page.replace(MARKER, sim)

# the claude.ai artifact copy (claude.ai adds its own document wrapper)
(ROOT / "dist").mkdir(exist_ok=True)
(ROOT / "dist" / "cheek-pouch.html").write_text(page, encoding="utf-8")

# the hosted page: the head above carries the charset and title, so drop the page's copies
site = page.replace('<meta charset="utf-8">\n', "").replace("<title>Cheek Pouch</title>\n", "", 1)
(ROOT / "index.html").write_text(HEAD + site + "\n</body></html>\n", encoding="utf-8")

# the server replays Daily Burrow runs with the very same core
(ROOT / "api" / "src" / "sim.gen.js").write_text(
    "// Generated by build.py from game/sim.js. Do not edit.\n" + sim + "\nexport default SIM;\n", encoding="utf-8")

print("wrote index.html, dist/cheek-pouch.html, api/src/sim.gen.js"
      + ("" if SITE_URL else " (set SITE_URL for full link previews)"))
